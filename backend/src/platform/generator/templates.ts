import type { ModuleTier } from '@erp/shared';
import type { ModuleNames } from './module-name';

/**
 * What a new module is on the day it is created.
 *
 * Not a skeleton with `TODO` in it. A generated module has a table, an endpoint that lists it
 * under the platform's conventions, a form that creates a row, a screen that shows the empty
 * state a fresh company actually sees, and tests for all of it — so `npm run check:modules`,
 * `npm run check:conformance` and both suites pass the moment it is generated, and the first
 * thing the person who asked for it does is *change* working code rather than fill in blanks.
 *
 * That is the difference between a generator and a snippet. A snippet leaves the interesting
 * decisions — how a list is paged, where the company filter goes, what an error body looks
 * like — to whoever is writing the eleventh module at four in the afternoon. Every one of
 * those decisions is already made here, and made the same way as in the three modules this
 * was extracted from.
 *
 * The templates are text rather than files copied from a real module, because a copied module
 * would carry its own domain with it and somebody would have to decide, per file, what to
 * strip. The cost is that these are not type-checked as they are written; what checks them is
 * that products was generated by them and is compiled by the build like everything else.
 */

/**
 * The frontend's entry point on the shared package, named indirectly.
 *
 * Written as a constant rather than inline in the template below, because the conformance
 * pack refuses that specifier in *any* file under `backend/` — the two entry points exist so
 * that Nest never acquires React — and it reads a file's import lines wherever they appear,
 * including inside a string holding a frontend module's source. The rule is right and this
 * file is the one legitimate exception to it, so it takes the indirection rather than the
 * rule taking an exemption: an exemption would be a hole in a rule about the whole backend,
 * and this is one word in one template.
 */
const SHARED_UI = '@erp/shared/ui';

