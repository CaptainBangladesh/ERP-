export function serviceFile(names: ModuleNames): string {
  const field = names.name.replace(/-/g, '');

  return `import { HttpStatus, Injectable } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import {
  ${names.recordConstant}_ERROR_CODES,
  type ${names.record}ListResponse,
  type ${names.record}Response,
  type ${names.record}Status,
  type ${names.record}Summary,
} from '@erp/shared';
import { ApiException } from '../../http/api-exception';
import { listQuery } from '../../platform/list';
import { companyApplied, InjectPrisma, type ScopedPrisma } from '../../platform/tenancy';
import type { Valid } from '../../platform/validation';
import { defined } from '../../prisma/columns';
import { Create${names.record}Body, ${names.recordConstant}_LIST, Update${names.record}Body } from './schemas';

/**
 * What ${names.words} actually does.
 *
 * Two things in here are the platform's rather than this module's, and both look like
 * omissions until you know why:
 *
 * - **There is no company filter anywhere.** Scoping is applied to every query below by the
 *   tenancy extension, so another company's rows are not reachable from this file even by
 *   trying. A module that wrote the filter would be a module that could forget it.
 * - **Nothing is deleted.** Deactivating keeps whatever refers to a record intelligible; a
 *   delete would leave it naming an identifier that resolves to nothing.
 */
@Injectable()
export class ${names.pascal}Service {
  constructor(@InjectPrisma() private readonly prisma: ScopedPrisma) {}

  async create${names.record}(
    input: Valid<typeof Create${names.record}Body>,
  ): Promise<${names.record}Response> {
    const ${field} = await this.prisma.${names.delegate}.create({
      data: companyApplied<Prisma.${names.record}UncheckedCreateInput>({ name: input.name }),
    });

    return describe(${field});
  }

  async list${names.record}s(query: Record<string, unknown>): Promise<${names.record}ListResponse> {
    const slice = listQuery(query, ${names.recordConstant}_LIST);

    const [rows, total] = await Promise.all([
      this.prisma.${names.delegate}.findMany(slice.findMany<Prisma.${names.record}FindManyArgs>()),
      this.prisma.${names.delegate}.count(slice.count<Prisma.${names.record}CountArgs>()),
    ]);

    return slice.respond(rows.map(describe), total);
  }

  async ${names.delegate}Detail(id: string): Promise<${names.record}Response> {
    const ${field} = await this.prisma.${names.delegate}.findFirst({ where: { id } });
    if (!${field}) throw notFound();

    return describe(${field});
  }

  /**
   * Changes a record, or deactivates it.
   *
   * Deactivation is a status rather than an endpoint of its own, because it is the same act
   * as any other correction from the caller's point of view and the same write from the
   * database's.
   */
  async change${names.record}(
    id: string,
    input: Valid<typeof Update${names.record}Body>,
  ): Promise<${names.record}Response> {
    await this.${names.delegate}Detail(id);

    const ${field} = await this.prisma.${names.delegate}.update({
      where: { id },
      data: { ...defined('name', input.name), ...defined('status', input.status) },
    });

    return describe(${field});
  }
}

function describe(row: { id: string; name: string; status: string }): ${names.record}Summary {
  return {
    id: row.id,
    name: row.name,
    // The column is text rather than a Postgres enum, so the wire type is asserted here, at
    // the one boundary where the two representations meet.
    status: row.status as ${names.record}Status,
  };
}

/**
 * The same 404 a record in another company gets, deliberately. Telling a caller that an
 * identifier is real but not theirs would turn the endpoint into a way of counting somebody
 * else's rows.
 */
function notFound(): ApiException {
  return new ApiException(
    ${names.recordConstant}_ERROR_CODES.${names.delegate}NotFound,
    'That ${names.recordWords} does not exist.',
    HttpStatus.NOT_FOUND,
  );
}
`;
}

export function schemasFile(names: ModuleNames): string {
  return `import { ${names.recordConstant}_FIELDS, ${names.recordConstant}_STATUSES, type ${names.record}Status } from '@erp/shared';
import type { ListSpec } from '../../platform/list';
import { oneOf, optional, text, validator } from '../../platform/validation';

/**
 * What this module accepts, and what it lets a caller ask of its list.
 *
 * Declared beside the module rather than in the platform, because the wording is the part
 * that belongs to whoever owns the screen: "Enter a name." and "Enter the ${names.recordWords}'s
 * name." are the same rule and different sentences.
 */

const ${names.recordConstant}_NAME = {
  missing: 'Enter a name.',
  maxLength: 200,
  tooLong: 'Use 200 characters or fewer.',
} as const;

const STATUS = oneOf<${names.record}Status>(${names.recordConstant}_STATUSES, {
  missing: 'Say whether this ${names.recordWords} is active.',
  invalid: 'That is not a status you can set.',
});

export const Create${names.record}Body = validator({
  name: text(${names.recordConstant}_NAME),
});

/** A change. Every field optional, at least one required — absent means "do not touch it". */
export const Update${names.record}Body = validator({
  name: optional(text(${names.recordConstant}_NAME)),
  status: optional(STATUS),
}).and((values, report) => {
  const changed = Object.values(values).some((value) => value !== undefined);
  if (!changed) report('name', 'Change something — this request changes nothing.');
});

/**
 * What a caller may do to the list.
 *
 * An allow-list: a field nobody names here is not reachable from a query string at all, so
 * '?sort=somethingPrivate' is refused before anything touches the database.
 */
export const ${names.recordConstant}_LIST: ListSpec = {
  defaultSort: ${names.recordConstant}_FIELDS.name,
  fields: {
    [${names.recordConstant}_FIELDS.name]: { type: 'text', sortable: true, filterable: true, searchable: true },
    [${names.recordConstant}_FIELDS.status]: { type: 'text', sortable: true, filterable: true },
    [${names.recordConstant}_FIELDS.createdAt]: { type: 'date', sortable: true, filterable: true },
  },
};
`;
}

